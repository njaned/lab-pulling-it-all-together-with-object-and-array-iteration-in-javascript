function getAllPlayers() {
  const data = gameObject();
  return Object.assign({}, data.home.players, data.away.players);
}


function numPointsScored(playerName) {
  const players = getAllPlayers();
  return players[playerName] ? players[playerName].points : null;
}


function shoeSize(playerName) {
  const players = getAllPlayers();
  return players[playerName] ? players[playerName].shoe : null;
}


function teamColors(teamName) {
  const data = gameObject();
  if (data.home.teamName === teamName) return data.home.colors;
  if (data.away.teamName === teamName) return data.away.colors;
  return [];
}


function teamNames() {
  const data = gameObject();
  return [data.home.teamName, data.away.teamName];
}


function playerNumbers(teamName) {
  const data = gameObject();
  let targetTeam = null;

  if (data.home.teamName === teamName) {
    targetTeam = data.home;
  } else if (data.away.teamName === teamName) {
    targetTeam = data.away;
  }

  if (!targetTeam) return [];

  return Object.values(targetTeam.players).map((player) => player.number);
}

// 6. Returns an object containing all stats for the given player
function playerStats(playerName) {
  const players = getAllPlayers();
  return players[playerName] || null;
}

function bigShoeRebounds() {
  const players = getAllPlayers();
  let maxShoeSize = -1;
  let rebounds = 0;

  for (const name in players) {
    const player = players[name];
    if (player.shoe > maxShoeSize) {
      maxShoeSize = player.shoe;
      rebounds = player.rebounds;
    }
  }

  return rebounds;
}